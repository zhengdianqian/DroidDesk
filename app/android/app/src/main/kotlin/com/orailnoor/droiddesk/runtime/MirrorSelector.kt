package com.orailnoor.droiddesk.runtime

import android.util.Log
import java.io.File
import java.net.HttpURLConnection
import java.net.URL

/**
 * Multi-mirror APT source selection for the rooted chroot.
 *
 * The stock ubuntu-base rootfs points at ports.ubuntu.com, which is
 * unreachable from many networks (especially in mainland China). This
 * helper probes a list of ARM64 "ubuntu-ports" mirrors with a HEAD
 * request (3 second timeout, no body downloaded) and writes the first
 * reachable one into <rootfs>/etc/apt/sources.list.
 *
 * The suite/codename (jammy, noble, ...) is read from the rootfs's own
 * /etc/os-release so the generated sources always match the installed
 * Ubuntu release and the arm64 architecture.
 */
object MirrorSelector {
    private const val TAG = "MirrorSelector"
    private const val PROBE_TIMEOUT_MS = 3000

    // Preference order: first reachable mirror wins.
    private val CANDIDATES = listOf(
        "http://mirrors.tuna.tsinghua.edu.cn/ubuntu-ports",
        "http://mirrors.ustc.edu.cn/ubuntu-ports",
        "http://mirrors.aliyun.com/ubuntu-ports",
    )

    /** Hostnames behind [CANDIDATES]; pinned into the chroot /etc/hosts. */
    val MIRROR_HOSTS: List<String> = CANDIDATES
        .mapNotNull { runCatching { java.net.URI(it).host }.getOrNull() }
        .distinct()

    /**
     * Read VERSION_CODENAME from the rootfs /etc/os-release so the
     * generated sources match the actual Ubuntu release (jammy, noble...).
     * Falls back to "noble" (the bundled ubuntu-base 24.04 rootfs).
     */
    fun detectCodename(rootfsDir: File): String {
        return try {
            val osRelease = File(rootfsDir, "etc/os-release")
            if (osRelease.exists()) {
                osRelease.readLines()
                    .firstOrNull { it.startsWith("VERSION_CODENAME=") }
                    ?.substringAfter('=')
                    ?.trim()
                    ?.takeIf { it.isNotEmpty() }
                    ?.let { return it }
            }
            "noble"
        } catch (e: Exception) {
            Log.w(TAG, "Failed to read os-release, defaulting to noble: ${e.message}")
            "noble"
        }
    }

    /**
     * Probe every candidate mirror with a ranged GET against
     * <mirror>/dists/<codename>/Release using a 3 second timeout.
     * Returns the reachable mirrors in preference order (possibly empty).
     *
     * GET with `Range: bytes=0-0` instead of HEAD: several CDNs (and the host proxy)
     * answer HEAD with 405/403, so HEAD-based probing reported a healthy mirror as
     * unavailable and the UI then claimed there was no usable mirror at all.
     */
    fun probeReachable(codename: String): List<String> {
        return CANDIDATES.filter { base -> probeOne(base, codename) }
    }

    private fun probeOne(base: String, codename: String): Boolean {
        val probeUrl = "$base/dists/$codename/Release"
        return try {
            val conn = URL(probeUrl).openConnection() as HttpURLConnection
            conn.requestMethod = "GET"
            conn.setRequestProperty("Range", "bytes=0-0")
            conn.connectTimeout = PROBE_TIMEOUT_MS
            conn.readTimeout = PROBE_TIMEOUT_MS
            conn.instanceFollowRedirects = true
            val code = conn.responseCode
            conn.disconnect()
            // Any HTTP answer proves the host is reachable; only a network error means
            // "cannot reach". A 404 is a mirror-layout problem, not an unreachable host.
            val reachable = code != -1
            Log.i(TAG, "Mirror probe $probeUrl -> HTTP $code (reachable=$reachable)")
            reachable
        } catch (e: Exception) {
            Log.i(TAG, "Mirror probe $probeUrl failed: ${e.javaClass.simpleName}: ${e.message}")
            false
        }
    }

    /** Coarse reachability used only to word error messages, never to block a switch. */
    enum class Reachability { REACHABLE, PARTIAL, UNREACHABLE }

    fun reachability(codename: String): Reachability {
        val reachable = probeReachable(codename).size
        return when {
            reachable == 0 -> Reachability.UNREACHABLE
            reachable == CANDIDATES.size -> Reachability.REACHABLE
            else -> Reachability.PARTIAL
        }
    }

    /**
     * Atomically write /etc/apt/sources.list inside the rootfs for the
     * given mirror and suite, using the ARM64 ubuntu-ports path, and
     * disable the stock deb822 ubuntu.sources so apt never contacts the
     * unreachable official archive.
     */
    fun writeSources(rootfsDir: File, mirrorBaseUrl: String, codename: String) {
        val suites = listOf(codename, "$codename-updates", "$codename-security", "$codename-backports")
        val body = buildString {
            append("# Generated by DroidDesk MirrorSelector (HEAD-probed, 3s timeout)\n")
            suites.forEach { suite ->
                append("deb [arch=arm64] $mirrorBaseUrl/ $suite main restricted universe multiverse\n")
            }
        }

        // Disable the stock deb822 file (ports.ubuntu.com) so apt-get
        // update does not fail on it. .disabled is not parsed by apt.
        val deb822 = File(rootfsDir, "etc/apt/sources.list.d/ubuntu.sources")
        if (deb822.exists()) {
            val disabled = File(rootfsDir, "etc/apt/sources.list.d/ubuntu.sources.disabled")
            if (disabled.exists()) disabled.delete()
            deb822.renameTo(disabled)
        }

        val sourcesList = File(rootfsDir, "etc/apt/sources.list")
        sourcesList.parentFile?.mkdirs()
        val tmp = File(rootfsDir, "etc/apt/sources.list.tmp")
        tmp.writeText(body)
        if (!tmp.renameTo(sourcesList)) {
            // rename can fail across odd filesystems; fall back to direct write
            sourcesList.writeText(body)
            tmp.delete()
        }
        Log.i(TAG, "Wrote APT sources for $mirrorBaseUrl ($codename, arm64)")
    }

    /**
     * Candidate mirrors ordered by probe result, with every unprobed candidate kept
     * as a fallback. A probe that fails (timeout, unresolvable host, proxy down) is
     * NOT evidence that the mirror is gone: probes run on the Android side and fail
     * as a group whenever the device resolver is broken. Callers must let apt-get
     * update decide instead of reporting "no mirror available".
     */
    fun orderedCandidates(codename: String): List<String> {
        val reachable = probeReachable(codename)
        return reachable + CANDIDATES.filterNot { it in reachable }
    }

    /**
     * Convenience: pick the best mirror and write it. When no probe succeeds the
     * preferred (first) candidate is still written so a broken probe cannot block a
     * mirror switch; only a write failure returns null.
     */
    fun applyBestMirror(rootfsDir: File): String? {
        val codename = detectCodename(rootfsDir)
        val chosen = orderedCandidates(codename).firstOrNull() ?: return null
        return runCatching {
            writeSources(rootfsDir, chosen, codename)
            chosen
        }.getOrNull()
    }
}
